'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..'), host = path.resolve(root, '../AppDock.at365');
const { launch, until } = require(path.join(host, 'scripts/page-test-host.cjs'));
const settings = require(path.join(host, 'out/main/shared/settings-schema')).createDefaultSettings();
const profile = path.join(root, '.artifacts', 'ui-' + Date.now());
const folder = path.join(profile, 'extensions', 'ChatCodex');
const node = path.join(host, '.tools', 'node', require(path.join(host, 'toolchain.json')).node, 'node.exe');
const portable = path.resolve(root, '../../40.ARTIFACT/AppDock.at365/AppDock.at365.exe');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'out/Applet.ChatCodex.at365/extension.json')));
fs.mkdirSync(folder, { recursive: true });
fs.cpSync(path.join(root, 'out/Applet.ChatCodex.at365'), folder, { recursive: true });
fs.copyFileSync(path.join(root, 'tests/fixtures/server.cjs'), path.join(folder, 'fixture.cjs'));
manifest.entry = 'fixture-entry.cjs';
fs.writeFileSync(path.join(folder, 'extension.json'), JSON.stringify(manifest));
const pidFile = path.join(profile, 'codex-pid.json');
fs.writeFileSync(path.join(folder, 'fixture-entry.cjs'),
  "const {createApplet}=require('./src/applet.cjs');const {CodexProcess}=require('./src/codex-process.cjs');" +
  'module.exports=createApplet({clientFactory:()=>{const c=new CodexProcess({command:{file:' + JSON.stringify(node) + ",args:[require('node:path').join(__dirname,'fixture.cjs')]}});" +
  "const start=c.start.bind(c);c.start=async()=>{await start();require('node:fs').writeFileSync(" + JSON.stringify(pidFile) + ",JSON.stringify(c.child.pid));};return c;}});");
settings.host.hardwareAcceleration = false; settings.host.closeToTray = false; settings.host.theme = 'light';
settings.globalShortcutCommands = []; settings.gestures.enabled = false;
settings.updates.checkHostOnStartup = false; settings.updates.checkAppletsOnStartup = false;
settings.extensions = { 'at365.chatcodex': { enabled: true, settings: {} } };
fs.writeFileSync(path.join(profile, 'settings.json'), JSON.stringify(settings));
const checks = [];
let instance;
(async () => {
  try {
    instance = await launch(profile, portable);
    await until(async () => (await instance.main.evaluate(() => window.dock.snapshot())).extensions.find(e => e.id === 'at365.chatcodex')?.state === 'running', 'Applet running');
    await instance.main.evaluate(() => window.dock.executeCommand('at365.chatcodex.open'));
    const page = await instance.page('/ChatCodex/web/index.html');
    await until(async () => (await page.getByTestId('status').textContent()).startsWith('接続済み'), 'fixture connected');
    assert.equal(await page.getByTestId('model').inputValue(), 'fixture-fast');
    await page.getByTestId('effort').selectOption('high');
    await until(() => page.getByTestId('effort').isEnabled(), 'selection saved');
    await page.getByTestId('input').fill('こんにちは');
    await page.getByTestId('input').press('Enter');
    await until(async () => (await page.getByTestId('conversation').textContent()).includes('fixture-fast/high'), 'chat response');
    checks.push('local page / model paging / effort selection / message and final item');
    await page.getByTestId('input').fill('質問');
    await page.getByTestId('input').press('Enter');
    await page.locator('[data-question-id="choice"]').selectOption('短く');
    await page.locator('[data-choice="answer"]').click();
    await until(async () => (await page.getByTestId('status').textContent()).startsWith('接続済み'), 'question answered');
    await page.getByTestId('input').fill('承認');
    await page.getByTestId('input').press('Enter');
    await page.locator('[data-choice="decline"]').click();
    await until(async () => (await page.getByTestId('status').textContent()).startsWith('接続済み'), 'approval answered');
    checks.push('inline question / approval reply');
    await page.getByTestId('input').fill('遅延');
    await page.getByTestId('input').press('Enter');
    await until(async () => (await page.getByTestId('send').textContent()) === '停止', 'stop available');
    await page.getByTestId('send').click();
    await until(async () => (await page.getByTestId('status').textContent()).includes('停止しました'), 'stopped');
    await page.getByTestId('new-chat').click();
    await until(() => page.locator('.message').count().then(n => n === 0), 'new conversation cleared');
    await page.getByTestId('input').fill('新しい会話');
    await page.getByTestId('input').press('Enter');
    await until(async () => (await page.getByTestId('conversation').textContent()).includes('応答: 新しい会話'), 'new conversation response');
    checks.push('stop / new conversation retains connection');
    await page.getByTestId('model').selectOption('fixture-simple');
    await until(async () => await page.getByTestId('effort').isDisabled(), 'no effort model');
    await page.getByTestId('input').fill('保持する下書き');
    await instance.save({ host: { theme: 'dark' } });
    await until(() => page.evaluate(() => document.documentElement.style.colorScheme === 'dark'), 'dark');
    await page.screenshot({ path: path.join(profile, 'dark.png') });
    await instance.resize(480, 650);
    await instance.save({ host: { theme: 'light' } });
    await until(() => page.evaluate(() => document.documentElement.style.colorScheme === 'light'), 'light');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(profile, 'narrow.png') });
    await instance.save({ extensionId: 'at365.chatcodex', pages: { main: { display: 'window' } } });
    assert.equal(await page.getByTestId('input').inputValue(), '保持する下書き');
    await instance.save({ extensionId: 'at365.chatcodex', pages: { main: { display: 'page' } } });
    assert.equal(await page.getByTestId('input').inputValue(), '保持する下書き');
    checks.push('light/dark / narrow / page-window relocation preserves draft');
    const pid = JSON.parse(fs.readFileSync(pidFile, 'utf8'));
    await instance.main.evaluate(() => window.dock.toggleExtension('at365.chatcodex', false));
    await until(() => page.isClosed(), 'page closed on deactivate');
    await until(() => { try { process.kill(pid, 0); return false; } catch { return true; } }, 'owned child exited');
    await instance.main.evaluate(() => window.dock.toggleExtension('at365.chatcodex', true));
    await until(async () => (await instance.main.evaluate(() => window.dock.snapshot())).extensions.find(e => e.id === 'at365.chatcodex')?.state === 'running', 'restart');
    await instance.main.evaluate(() => window.dock.executeCommand('at365.chatcodex.open'));
    const restored = await instance.page('/ChatCodex/web/index.html');
    await until(async () => (await restored.getByTestId('status').textContent()).startsWith('接続済み'), 'reconnected');
    assert.equal(await restored.getByTestId('model').inputValue(), 'fixture-simple');
    assert.equal(await restored.locator('.message').count(), 0);
    checks.push('deactivate reaps child / restart restores selection only');
    const runtime = await instance.app.evaluate(({ app }) => ({ version: app.getVersion() }));
    const result = { ok: true, fixture: true, runtime, hostSha256: instance.hash, checks };
    await instance.close(); instance = null;
    fs.writeFileSync(path.join(profile, 'result.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify({ ...result, profile }));
  } finally { await instance?.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
